buf_t from_hex(const char* hex) {
  buf_t out;
  EXPECT_TRUE(strext::from_hex(out, std::string(hex)));
  return out;
}

// Presig blob codec (mirrors src/cbmpc/api/ecdsa2pc.cpp).
struct presig_blob_v1_t {
  uint32_t version = 1;
  uint32_t role = 0;   // 0=p1, 1=p2
  uint32_t curve = 0;  // coinbase::api::curve_id
  buf_t sid;
  std::vector<coinbase::crypto::bn_t> k;
  std::vector<coinbase::crypto::ecc_point_t> R;
  std::vector<coinbase::crypto::ecc_point_t> R2;

  void convert(coinbase::converter_t& c) { c.convert(version, role, curve, sid, k, R, R2); }
};

void expect_valid(mem_t msg_hash, const buf_t& sig) {
  ASSERT_FALSE(sig.empty());
  buf_t pub = from_hex(kPublicKeyHex);
  coinbase::crypto::ecc_point_t Q;
  ASSERT_EQ(Q.from_bin(coinbase::crypto::curve_secp256k1, pub), SUCCESS);
  EXPECT_EQ(coinbase::crypto::ecc_pub_key_t(Q).verify(msg_hash, sig), SUCCESS);
}

// Both key blobs give the same public key, and both presig blobs decode as presigs of this key's curve, one per
// role, with three slots and the same nonce points.
TEST(ApiEcdsa2pcPresignBlobs, OldBlobsLoad) {
  const buf_t key1 = from_hex(kP1KeyBlobHex);
  const buf_t key2 = from_hex(kP2KeyBlobHex);
  buf_t pub1, pub2;
  ASSERT_EQ(api::get_public_key_compressed(key1, pub1), SUCCESS);
  ASSERT_EQ(api::get_public_key_compressed(key2, pub2), SUCCESS);
  EXPECT_EQ(pub1, pub2);
  EXPECT_EQ(pub1, from_hex(kPublicKeyHex));

  presig_blob_v1_t p1, p2;
  ASSERT_EQ(coinbase::convert(p1, from_hex(kP1PresigBlobHex)), SUCCESS);
  ASSERT_EQ(coinbase::convert(p2, from_hex(kP2PresigBlobHex)), SUCCESS);
  EXPECT_EQ(p1.version, 1u);
  EXPECT_EQ(p2.version, 1u);
  EXPECT_EQ(p1.role, 0u);
  EXPECT_EQ(p2.role, 1u);
  EXPECT_EQ(p1.curve, static_cast<uint32_t>(coinbase::api::curve_id::secp256k1));
  EXPECT_EQ(p2.curve, static_cast<uint32_t>(coinbase::api::curve_id::secp256k1));
  EXPECT_EQ(p1.sid, p2.sid);
  ASSERT_EQ(p1.k.size(), 3u);
  ASSERT_EQ(p2.k.size(), 3u);
  const coinbase::crypto::ecurve_t curve = coinbase::crypto::curve_secp256k1;
  for (size_t i = 0; i < 3; i++) {
    ASSERT_EQ(p1.R[i].get_curve(), curve);
    EXPECT_EQ(curve.check(p1.R[i]), SUCCESS);
    EXPECT_EQ(curve.check(p1.R2[i]), SUCCESS);
    EXPECT_EQ(p1.R[i], p2.R[i]);
    EXPECT_EQ(p1.R2[i], p2.R2[i]);
  }
}

// Message 4 written by the old library for slot 0 is finished by this library into a valid signature.
TEST(ApiEcdsa2pcPresignBlobs, OldMessage4FinishesHere) {
  const buf_t key1 = from_hex(kP1KeyBlobHex);
  const buf_t presig1 = from_hex(kP1PresigBlobHex);
  const buf_t msg_hash = from_hex(kMsgHashSlot0Hex);
  const buf_t msg4 = from_hex(kMsg4Slot0Hex);
  buf_t sig;
  ASSERT_EQ(api::presign_finish(key1, presig1, 0, msg_hash, msg4, sig), SUCCESS);
  expect_valid(msg_hash, sig);
}

// Slot 1 of the old blobs completes and finishes in this library into a valid signature.
TEST(ApiEcdsa2pcPresignBlobs, OldBlobsCompleteAndFinishHere) {
  const buf_t key1 = from_hex(kP1KeyBlobHex);
  const buf_t key2 = from_hex(kP2KeyBlobHex);
  const buf_t presig1 = from_hex(kP1PresigBlobHex);
  const buf_t presig2 = from_hex(kP2PresigBlobHex);
  buf_t msg_hash(32);
  for (int i = 0; i < 32; i++) msg_hash[i] = static_cast<uint8_t>(0x60 + i);

  buf_t msg4, sig;
  ASSERT_EQ(api::presign_complete(key2, presig2, 1, msg_hash, msg4), SUCCESS);
  ASSERT_FALSE(msg4.empty());
  ASSERT_EQ(api::presign_finish(key1, presig1, 1, msg_hash, msg4, sig), SUCCESS);
  expect_valid(msg_hash, sig);
}

